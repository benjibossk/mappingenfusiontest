export type Key = keyof typeof fr

const langs: Record<string, Partial<Record<Key, string>>> = { fr }

let lang = 'fr'
try {
  lang = localStorage.getItem('reforger-mapper.lang') ?? 'fr'
} catch { /* storage blocked */ }

export function setLang(code: string) {
  if (langs[code]) lang = code
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  const s: string = langs[lang]?.[key] ?? fr[key]
  return vars ? s.replace(/\{(\w+)\}/g, (m, n: string) => (n in vars ? String(vars[n]) : m)) : s
}
